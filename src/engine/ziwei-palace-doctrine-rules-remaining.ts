import type { LifeDomain } from "./engine-v2";
import type { ZiweiCompanionModifier, ZiweiPalaceDoctrineRule } from "./ziwei-palace-doctrine-rules";

type RuleSeed = readonly [
  mainStar: string,
  normalizedReading: string,
  companionModifiers?: readonly ZiweiCompanionModifier[],
  brightnessSensitive?: boolean
];

const modifier = (allStars: string[], normalizedReading: string): ZiweiCompanionModifier => ({ allStars, normalizedReading });

function palaceRules(
  idPart: string,
  domain: LifeDomain,
  palaceNames: string[],
  section: string,
  seeds: readonly RuleSeed[],
  boundary?: string
): ZiweiPalaceDoctrineRule[] {
  return seeds.map(([mainStar, normalizedReading, companionModifiers = [], brightnessSensitive = true]) => ({
    id: `ZW2-${idPart}-${mainStar}`,
    domain,
    palaceNames,
    mainStar,
    normalizedReading,
    companionModifiers: [...companionModifiers],
    brightnessSensitive,
    disruptiveSensitive: true,
    section: `권2·${section}·${mainStar}`,
    boundary
  }));
}

